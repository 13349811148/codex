def classify_record(record: NormalizedRecord) -> NormalizedRecord:
    if record.platform in TAOBAO_LIKE_PLATFORMS:
        if record.remark_norm == "[空]" and record.biz_desc == "[空]":
            record.ignored = True
            record.detail_category = "不统计"
            record.major_category = "忽略"
            return record

        key = f"{record.remark_norm} —— {record.biz_desc}"
        matched = TAOBAO_RULES.get(key)
        if not matched:
            record.detail_category = "暂未分类"
            record.major_category = "暂未分类"
            record.warning_message = _build_unmapped_warning(record.store_name, key)
            return record

        record.detail_category, record.major_category = matched
        return record

    if record.platform == "拼多多":
        matched = PDD_RULES.get(record.biz_desc)
        if not matched:
            record.detail_category = "暂未分类"
            record.major_category = "暂未分类"
            record.warning_message = _build_unmapped_warning(record.store_name, record.biz_desc)
            return record

        record.detail_category, record.major_category = matched
        return record

    record.error_message = f"{record.source_file}: 暂不支持的平台 {record.platform}"
    return record


def _build_unmapped_warning(store_name: str, item_text: str) -> str:
    return (
        f"店铺{store_name}账单表格中的业务描述项：{item_text} 未做分类映射，"
        "请及时联系软件开发方维护更新，以便于后续的统计工作。"
    )
